public class CCC {
	
	// public 이 있어야 부를수가 있다
	String a = "p2.CCC.a";
	void mm1() {
		System.out.println("p2.CCC.mm1() 실행");
	}
	
	public String b = "p2.CCC.public_b";
	public void mm2() {
		System.out.println("p2.CCC.public_mm2() 실행");
	}
}


