package basic_p;

public class VarOrderMain {

	public static void main(String[] args) {
		String coname = "아프리카노";
		boolean fo = true;
		char size = 'L';
		int mo = 2100;
		short ss = 3;
		int gg = 6300;
		
		
		System.out.println("커피이름 :" +coname);
		System.out.println("포장유무:" +fo);
		System.out.println(size);
		System.out.println(mo);
		System.out.println(ss);
		System.out.println(gg);
		System.out.println(gg);

	}

}
